#!/usr/bin/env node
// Nudge — agent-side setup on WINDOWS (per user, once). The macOS/Linux
// installer is setup-agent.sh; this one installs the same pieces:
//
//   - the groundworks-nudge command in ~/.local/bin, as two small launchers:
//     groundworks-nudge.cmd (cmd and PowerShell) and an extensionless sh script
//     (Git Bash, which Claude Code uses for its shell). No .ps1: the default
//     execution policy would block it instead of falling back to the .cmd.
//   - the Skill /groundworks-nudge for Claude Code, Codex and Grok Build,
//   - the optional Claude Code and Codex hooks.
//
// Usage: node agent/setup-agent.mjs [all|claude-code|codex] [--uninstall]
//
// Idempotent. Existing settings and unrelated hooks are preserved; a settings
// file that does not parse is left alone with a warning, never overwritten.
// --uninstall removes only what this script installed; the Nudge store
// (~/.nudge) with your prompts and screenshots stays.
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.dirname(HERE)
const HOME = os.homedir()
const args = process.argv.slice(2)
const UNINSTALL = args.includes('--uninstall')
const RUNTIME = args.find((a) => !a.startsWith('--')) || 'all'

if (process.platform !== 'win32') {
  console.error('error: this installer is for Windows. On macOS/Linux run ./agent/setup-agent.sh')
  process.exit(1)
}
if (!['all', 'claude-code', 'codex'].includes(RUNTIME)) {
  console.error('usage: node agent/setup-agent.mjs [all|claude-code|codex] [--uninstall]')
  process.exit(2)
}

const BIN_HOME = path.join(HOME, '.local', 'bin')
const MARKER = 'Generated by Groundworks Nudge setup-agent.mjs'
const CLI = path.join(HERE, 'groundworks-nudge.mjs')
const slash = (p) => p.replace(/\\/g, '/') // one spelling that bash, cmd and PowerShell all accept
const shQuote = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`
const LAUNCHERS = {
  [path.join(BIN_HOME, 'groundworks-nudge.cmd')]: [
    '@echo off',
    `rem ${MARKER}. Re-run it after moving the repository.`,
    `node "${CLI.replace(/%/g, '%%')}" %*`,
    '',
  ].join('\r\n'),
  [path.join(BIN_HOME, 'groundworks-nudge')]: [
    '#!/bin/sh',
    `# ${MARKER}. Re-run it after moving the repository.`,
    `exec node ${shQuote(slash(CLI))} "$@"`,
    '',
  ].join('\n'),
}

const HOOK_FILES = ['nudge-context.mjs', 'runtime.mjs', 'nudge-session-start.mjs']
// Hook entries are recognised by these names. The .sh name also matches, so a
// settings file carried over from macOS/Linux is repaired instead of doubled.
const HOOK_EVENTS = {
  SessionStart: { match: 'nudge-session-start.', command: (dir) => `node "${slash(path.join(dir, 'nudge-session-start.mjs'))}" "${slash(path.join(ROOT, 'bridge', 'bridge.mjs'))}"` },
  UserPromptSubmit: { match: 'nudge-context.mjs', command: (dir) => `node "${slash(path.join(dir, 'nudge-context.mjs'))}"` },
}
const RUNTIMES = {
  codex: { skills: path.join(HOME, '.agents', 'skills'), hooks: path.join(HOME, '.codex', 'hooks'), config: path.join(HOME, '.codex', 'hooks.json') },
  'claude-code': { skills: path.join(HOME, '.claude', 'skills'), hooks: path.join(HOME, '.claude', 'hooks'), config: path.join(HOME, '.claude', 'settings.json') },
}
const GROK_SKILLS = path.join(HOME, '.grok', 'skills')
const selected = RUNTIME === 'all' ? ['codex', 'claude-code'] : [RUNTIME]

const isOurs = (file) => { try { return fs.readFileSync(file, 'utf8').includes(MARKER) } catch { return false } }
const sameAsRepo = (file, source) => { try { return fs.readFileSync(file).equals(fs.readFileSync(source)) } catch { return false } }

function readJson(file) {
  if (!fs.existsSync(file)) return { ok: true, data: {} }
  try {
    const text = fs.readFileSync(file, 'utf8').replace(/^﻿/, '') // editors on Windows like a BOM
    const data = text.trim() ? JSON.parse(text) : {}
    if (!data || typeof data !== 'object' || Array.isArray(data)) return { ok: false }
    return { ok: true, data }
  } catch { return { ok: false } }
}
function writeJsonIfChanged(file, before, after) {
  if (JSON.stringify(before) === JSON.stringify(after)) return false
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, `${JSON.stringify(after, null, 2)}\n`)
  return true
}

// Same merge as setup-agent.sh: keep every foreign hook, keep exactly one Nudge
// entry per event, refresh its command.
function mergeHooks(settings, hooksDir) {
  const next = structuredClone(settings)
  next.hooks = next.hooks && typeof next.hooks === 'object' ? next.hooks : {}
  for (const [event, spec] of Object.entries(HOOK_EVENTS)) {
    const command = spec.command(hooksDir)
    const groups = Array.isArray(next.hooks[event]) ? next.hooks[event] : []
    let found = false
    const out = []
    for (const group of groups) {
      const hooks = []
      for (const hook of Array.isArray(group.hooks) ? group.hooks : []) {
        if (!String(hook.command || '').includes(spec.match)) hooks.push(hook)
        else if (!found) { hooks.push({ ...hook, type: 'command', command, timeout: 15, statusMessage: 'Nudge…' }); found = true }
      }
      if (hooks.length || !Array.isArray(group.hooks)) out.push({ ...group, hooks })
    }
    if (!found) out.push({ hooks: [{ type: 'command', command, timeout: 15, statusMessage: 'Nudge…' }] })
    next.hooks[event] = out
  }
  return next
}
function removeHooks(settings) {
  const next = structuredClone(settings)
  if (!next.hooks || typeof next.hooks !== 'object') return next
  for (const [event, spec] of Object.entries(HOOK_EVENTS)) {
    if (!Array.isArray(next.hooks[event])) continue
    const out = []
    for (const group of next.hooks[event]) {
      if (!Array.isArray(group.hooks)) { out.push(group); continue }
      const hooks = group.hooks.filter((hook) => !String(hook.command || '').includes(spec.match))
      if (hooks.length) out.push({ ...group, hooks })
    }
    if (out.length) next.hooks[event] = out
    else delete next.hooks[event]
  }
  if (!Object.keys(next.hooks).length) delete next.hooks
  return next
}

function removeLegacyAlias(skillsHome) {
  const file = path.join(skillsHome, 'nudge', 'SKILL.md')
  if (!fs.existsSync(file)) return
  const text = fs.readFileSync(file, 'utf8')
  if (text.includes('name: nudge') && text.includes('Compatibility alias for groundworks-nudge')) {
    fs.rmSync(file)
    try { fs.rmdirSync(path.dirname(file)) } catch { /* not empty */ }
  } else console.error(`preserved: ${file} is not the Groundworks Nudge compatibility alias`)
}

function install() {
  fs.mkdirSync(BIN_HOME, { recursive: true })
  for (const file of Object.keys(LAUNCHERS)) {
    if (fs.existsSync(file) && !isOurs(file)) {
      console.error(`refused: ${file} exists and was not written by this installer`)
      process.exit(3)
    }
  }
  for (const [file, text] of Object.entries(LAUNCHERS)) fs.writeFileSync(file, text)

  const skillHomes = selected.map((r) => RUNTIMES[r].skills)
  if (RUNTIME === 'all') skillHomes.push(GROK_SKILLS)
  for (const home of skillHomes) {
    fs.mkdirSync(path.join(home, 'groundworks-nudge'), { recursive: true })
    fs.copyFileSync(path.join(HERE, 'NUDGE-SKILL.md'), path.join(home, 'groundworks-nudge', 'SKILL.md'))
    removeLegacyAlias(home)
  }

  for (const r of selected) {
    const { hooks, config } = RUNTIMES[r]
    fs.mkdirSync(hooks, { recursive: true })
    for (const f of HOOK_FILES) fs.copyFileSync(path.join(HERE, f), path.join(hooks, f))
    const current = readJson(config)
    if (!current.ok) { console.error(`skipped: ${config} is not valid JSON; fix it and re-run to add the Nudge hooks`); continue }
    writeJsonIfChanged(config, current.data, mergeHooks(current.data, hooks))
    console.log(`${path.basename(config)}: Nudge hooks active (SessionStart + UserPromptSubmit)`)
  }

  console.log(`installed: ${path.join(BIN_HOME, 'groundworks-nudge.cmd')} · groundworks-nudge (${RUNTIME})`)
  const onPath = (process.env.PATH || '').split(path.delimiter)
    .some((dir) => dir && path.resolve(dir).toLowerCase() === BIN_HOME.toLowerCase())
  if (!onPath) {
    console.log('')
    console.log(`${BIN_HOME} is not on your PATH yet. Add it once (PowerShell), then restart`)
    console.log('your terminals, T3 Code and other agent apps so they see the command:')
    console.log(`  [Environment]::SetEnvironmentVariable('Path', [Environment]::GetEnvironmentVariable('Path', 'User') + ';${BIN_HOME}', 'User')`)
  }
  console.log('')
  console.log('Next: in an agent session on the project you want to change, invoke:')
  console.log('  /groundworks-nudge')
  console.log('Then open http://localhost:4700/demo in Chrome and wait for the green status dot.')
  console.log('T3 Code: open a thread on that project and type /groundworks-nudge (or pick it from $).')
}

function uninstall() {
  const report = (what, file) => console.log(`${what}: ${file}`)
  for (const file of Object.keys(LAUNCHERS)) {
    if (!fs.existsSync(file)) continue
    if (isOurs(file)) { fs.rmSync(file); report('removed', file) } else report('kept (not ours)', file)
  }
  const skillHomes = selected.map((r) => RUNTIMES[r].skills)
  if (RUNTIME === 'all') skillHomes.push(GROK_SKILLS)
  for (const home of skillHomes) {
    const file = path.join(home, 'groundworks-nudge', 'SKILL.md')
    if (!fs.existsSync(file)) continue
    if (/^name: groundworks-nudge$/m.test(fs.readFileSync(file, 'utf8'))) {
      fs.rmSync(file)
      try { fs.rmdirSync(path.dirname(file)) } catch { /* the user keeps other files there */ }
      report('removed', file)
    } else report('kept (not ours)', file)
  }
  for (const r of selected) {
    const { hooks, config } = RUNTIMES[r]
    for (const f of HOOK_FILES) {
      const file = path.join(hooks, f)
      if (!fs.existsSync(file)) continue
      // runtime.mjs is a generic name: remove a copy only when it is ours byte for byte
      if (sameAsRepo(file, path.join(HERE, f)) || f !== 'runtime.mjs') { fs.rmSync(file); report('removed', file) } else report('kept (differs from Nudge)', file)
    }
    const current = readJson(config)
    if (!current.ok) { console.error(`skipped: ${config} is not valid JSON; remove the Nudge hooks by hand`); continue }
    if (writeJsonIfChanged(config, current.data, removeHooks(current.data))) report('Nudge hooks removed in', config)
  }
  const store = path.join(HOME, '.nudge')
  console.log('')
  console.log(`Kept your data: ${fs.existsSync(store) ? store : `${store} (not created yet)`}. Delete it yourself if you want the prompts and screenshots gone.`)
}

if (UNINSTALL) uninstall()
else install()
